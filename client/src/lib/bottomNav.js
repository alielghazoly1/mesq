// الصفحات اللي الشريط السفلي (الموبايل) بيظهر فيها.
//
// في مكان واحد عشان الشريط نفسه وزرار الدعم العايم بيسألوا نفس السؤال:
// لو الشريط ظاهر، زرار الدعم العايم بيستخبى على الموبايل (أيقونة "الدعم"
// في الشريط بتفتح نفس اللوحة) — ولو مش ظاهر، الزرار العايم يرجع.
//
// بيتشال من:
//   • المحرر وصفحة ملء بيانات التصميم: شاشة شغل، والشريط هياكل منها مساحة
//     وهياخد ضغطات بالغلط.
//   • لوحة التحكم: دي بتاعة صاحب الموقع مش العميل.
//   • صفحة الدفع: عندها شريط ثابت تحت بالمبلغ وزرار رفع الإيصال — ده
//     أهم زرار في الموقع ومينفعش حاجة تغطّيه أو تشتّت عنه.
const HIDDEN_PREFIXES = ['/editor/', '/admin', '/checkout/', '/create/'];

/** @param {string} pathname */
export function hasBottomNav(pathname) {
  return !HIDDEN_PREFIXES.some((p) => pathname.startsWith(p));
}
